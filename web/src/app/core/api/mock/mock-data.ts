/** Samedi prochain (+ `offset` jours), pour simuler une indisponibilité le week-end. */
const nextSaturday = (offset = 0, hour = 9): IsoDateTime => {
  const d = new Date();
  return daysFromNow(((6 - d.getDay() + 7) % 7 || 7) + offset, hour);
};

