/** Date relative à aujourd'hui, pour que les données fictives restent crédibles. */
const daysFromNow = (days: number, hour = 9): IsoDateTime => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString() as IsoDateTime;
};

